import sharp from 'sharp'
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const manifest = JSON.parse(readFileSync(resolve(root, 'public/illustrations/commands/manifest.json'), 'utf8'))
const images = {}
const report = { widths: [160, 320, 640], originalBytes: 0, variantBytes: { 160: 0, 320: 0, 640: 0 }, cards: [] }
for (const card of manifest.cards) {
  const input = readFileSync(resolve(root, 'assets/card-originals', card.path))
  report.originalBytes += input.length
  const variants = {}
  const sizes = []
  for (const width of report.widths) {
    const path = `responsive/${card.path.replace(/\.png$/, `-${width}.webp`)}`
    const output = resolve(root, 'public/illustrations', path)
    mkdirSync(dirname(output), { recursive: true })
    const { data, info } = await sharp(input).resize({ width, withoutEnlargement: true }).webp({ quality: 88, effort: 6 }).toBuffer({ resolveWithObject: true })
    writeFileSync(output, data)
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 12)
    variants[width] = `${path}?v=${hash}`
    report.variantBytes[width] += data.length
    sizes.push({ path, width: info.width, height: info.height, bytes: data.length })
  }
  images[card.en] = variants
  report.cards.push({ en: card.en, variants: sizes })
}
writeFileSync(resolve(root, 'src/data/responsiveImages.ts'), `// Generated by scripts/resize-cards.mjs.\nexport const responsiveImages: Record<string, Record<number, string>> = ${JSON.stringify(images, null, 2)}\n`)
writeFileSync(resolve(root, 'docs/responsive-images-report.json'), `${JSON.stringify(report, null, 2)}\n`)
console.log(`Resized ${manifest.cards.length} cards: ${JSON.stringify(report.variantBytes)} bytes (original ${report.originalBytes}).`)
