import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const manifest = JSON.parse(readFileSync(resolve(root, 'public/illustrations/commands/manifest.json'), 'utf8'))
const files = new Map()
const groups = new Map()
const images = {}

// ZIP entries use the stored format: PNGs are already compressed.
const crcTable = Array.from({ length: 256 }, (_, i) => {
  let crc = i
  for (let bit = 0; bit < 8; bit++) crc = crc & 1 ? 0xedb88320 ^ (crc >>> 1) : crc >>> 1
  return crc >>> 0
})
function crc32(data) {
  let crc = 0xffffffff
  for (const byte of data) crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}
function zip(entries) {
  const locals = [], centrals = []
  let offset = 0
  for (const { name, data } of entries) {
    const filename = Buffer.from(name)
    const crc = crc32(data)
    const local = Buffer.alloc(30)
    local.writeUInt32LE(0x04034b50, 0)
    local.writeUInt16LE(20, 4)
    local.writeUInt16LE(0x21, 12) // Fixed 1980-01-01 date for reproducible archives.
    local.writeUInt32LE(crc, 14)
    local.writeUInt32LE(data.length, 18)
    local.writeUInt32LE(data.length, 22)
    local.writeUInt16LE(filename.length, 26)
    const central = Buffer.alloc(46)
    central.writeUInt32LE(0x02014b50, 0)
    central.writeUInt16LE(20, 4)
    central.writeUInt16LE(20, 6)
    central.writeUInt16LE(0x21, 14)
    central.writeUInt32LE(crc, 16)
    central.writeUInt32LE(data.length, 20)
    central.writeUInt32LE(data.length, 24)
    central.writeUInt16LE(filename.length, 28)
    central.writeUInt32LE(offset, 42)
    locals.push(local, filename, data)
    centrals.push(central, filename)
    offset += local.length + filename.length + data.length
  }
  const directory = Buffer.concat(centrals)
  const end = Buffer.alloc(22)
  end.writeUInt32LE(0x06054b50, 0)
  end.writeUInt16LE(entries.length, 8)
  end.writeUInt16LE(entries.length, 10)
  end.writeUInt32LE(directory.length, 12)
  end.writeUInt32LE(offset, 16)
  return Buffer.concat([...locals, directory, end])
}

for (const card of manifest.cards) {
  const data = readFileSync(resolve(root, 'public/illustrations', card.path))
  if (!data.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) throw new Error(`Invalid PNG: ${card.path}`)
  files.set(card.path, data)
  const hash = createHash('sha256').update(data).digest('hex').slice(0, 12)
  images[card.en] = `${card.path}?v=${hash}`
  for (const id of card.cardIds) {
    const [, deckId, position] = id.match(/^(.*)-(\d+)$/) ?? []
    if (!deckId) throw new Error(`Invalid card id: ${id}`)
    if (!groups.has(deckId)) groups.set(deckId, [])
    groups.get(deckId).push({ position: Number(position), card })
  }
}
writeFileSync(resolve(root, 'src/data/commandImages.ts'), `// Generated by scripts/package-cards.mjs. English captions must match exactly.\nexport const commandImages: Record<string, string> = ${JSON.stringify(images, null, 2)}\n`)
mkdirSync(resolve(root, 'public/downloads'), { recursive: true })
for (const [deckId, rows] of groups) {
  rows.sort((a, b) => a.position - b.position)
  const entries = rows.map(({ position, card }) => ({
    name: `${String(position).padStart(2, '0')}-${card.path.split('/').at(-1)}`,
    data: files.get(card.path),
  }))
  writeFileSync(resolve(root, 'public/downloads', `${deckId}.zip`), zip(entries))
}
// Keep the original one-year download URL serving the current optimized cards.
copyFileSync(resolve(root, 'public/downloads/baby-first.zip'), resolve(root, 'public/illustrations/one-year/tpr-one-year-cards.zip'))
console.log(`Packaged ${manifest.cards.length} standalone images covering ${[...groups.values()].reduce((n, rows) => n + rows.length, 0)} cards in ${groups.size} deck archives.`)
