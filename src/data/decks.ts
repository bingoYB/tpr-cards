import type { AgeGroup, TprDeck } from '@/types'
import { ageDecks } from './ageDecks'

const legacyAges: Record<string, AgeGroup> = { classroom: '4-6', body: '3', animals: '3', daily: '2', feelings: '2', directions: '4-6', 'numbers-colors': '4-6' }

type Row = [emoji: string, en: string, zh: string]

function deck(
  id: string,
  name: string,
  emoji: string,
  color: string,
  description: string,
  rows: Row[],
): TprDeck {
  return {
    id,
    name,
    emoji,
    color,
    description,
    builtIn: true,
    ageGroup: legacyAges[id],
    cards: rows.map(([emoji, en, zh], i) => ({ id: `${id}-${i + 1}`, emoji, en, zh })),
  }
}

